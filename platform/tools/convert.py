#!/usr/bin/env python3
"""Rewrite each HG app's Supabase migrations from the `public` schema into its own
schema, and emit one ordered migration chain for the shared HG Supabase project.

usage: convert.py <uploads_root> <out_dir>
"""
import os
import re
import sys

APPS = [
    # (source repo folder, target schema, hour slot, private-schema renames)
    ("people-hg", "people", "01", {}),
    ("HG-Claims", "claims", "02", {"private": "claims_private"}),
    ("lms-hg", "lms", "03", {"app_private": "lms_private"}),
    ("drip-n-brew", "pos", "04", {}),
]

DATE = "20261201"

# A search_path setting: `search_path = a, b` / `search_path TO a, b` / set_config('search_path', 'a, b', ..)
SEARCH_PATH_RE = re.compile(
    r"(search_path\s*(?:=|TO)\s*)([^;\n]*?)(?=\s+AS\b|\s*;|\s*\n|\s*\$|$)", re.IGNORECASE
)


def rewrite_search_path(sql: str, schema: str) -> str:
    def fix_list(m: re.Match) -> str:
        head, body = m.group(1), m.group(2)
        parts = [p.strip() for p in body.split(",")]
        new = []
        for p in parts:
            bare = p.strip("'\"")
            if bare == "public":
                q = p[0] if p[:1] in "'\"" else ""
                new.append(f"{q}{schema}{q}")
            else:
                new.append(p)
        return head + ", ".join(new)

    return SEARCH_PATH_RE.sub(fix_list, sql)


def convert(sql: str, schema: str, renames: dict) -> str:
    # 1. private helper schemas get app-specific names so apps can't collide.
    for old, new in renames.items():
        sql = re.sub(rf"(?<![\w.\"]){old}\.", f"{new}.", sql)
        sql = re.sub(rf"(\bSCHEMA\s+(?:IF\s+NOT\s+EXISTS\s+)?){old}\b", rf"\g<1>{new}", sql, flags=re.I)
        sql = sql.replace(f"'{old}'", f"'{new}'")
        sql = re.sub(rf"(search_path\s*(?:=|TO)\s*[^;\n]*?)\b{old}\b", rf"\g<1>{new}", sql, flags=re.I)
    # 2. Qualified references public.x / "public".x
    sql = re.sub(r'(?<![\w."])public\.', f"{schema}.", sql)
    sql = re.sub(r'(?<![\w.])"public"\.', f'"{schema}".', sql)
    # 3. Schema-level statements: GRANT .. ON SCHEMA public, IN SCHEMA public, ALTER DEFAULT PRIVILEGES IN SCHEMA public
    sql = re.sub(r"(\bSCHEMA\s+)public\b", rf"\g<1>{schema}", sql, flags=re.I)
    # 4. search_path lists
    sql = rewrite_search_path(sql, schema)
    # 5. Catalog lookups that name the schema as a string ('public', 'public'::regnamespace)
    sql = sql.replace("'public'", f"'{schema}'")
    # 6. Extensions not preinstalled on Supabase go to the extensions schema, never an app schema.
    sql = re.sub(r"(CREATE\s+EXTENSION\s+IF\s+NOT\s+EXISTS\s+\"?pg_trgm\"?)(\s*;)",
                 r"\1 WITH SCHEMA extensions\2", sql, flags=re.I)
    return sql


def main(root: str, out: str) -> None:
    os.makedirs(out, exist_ok=True)
    mapping = []
    for repo, schema, hour, renames in APPS:
        src_dir = os.path.join(root, repo, "supabase", "migrations")
        files = sorted(f for f in os.listdir(src_dir) if f.endswith(".sql"))
        for i, name in enumerate(files, start=1):
            assert i < 60, "slot overflow"
            src = open(os.path.join(src_dir, name), encoding="utf-8").read()
            body = convert(src, schema, renames)
            stem = re.sub(r"^\d+_", "", name[:-4])
            version = f"{DATE}{hour}00{i:02d}"
            new_name = f"{version}_{schema}_{stem}.sql"
            header = (
                f"-- HG shared platform migration (schema: {schema})\n"
                f"-- Source: {repo}/supabase/migrations/{name}\n"
                f"-- Generated by platform/tools/convert.py: references to the public schema were\n"
                f"-- rewritten to `{schema}`" + (
                    "; private schemas renamed " + ", ".join(f"{k} -> {v}" for k, v in renames.items())
                    if renames else "") + ".\n"
                f"-- Edit the source app's migration history only until the cutover; after that, edit here.\n\n"
                f"SET search_path TO {schema}, extensions;\n\n"
            )
            with open(os.path.join(out, new_name), "w", encoding="utf-8") as fh:
                fh.write(header + body)
            mapping.append((repo, name, new_name))
    with open(os.path.join(out, "..", "..", "MIGRATION_MAP.csv"), "w", encoding="utf-8") as fh:
        fh.write("source_repo,source_file,platform_file\n")
        for row in mapping:
            fh.write(",".join(row) + "\n")
    print(f"wrote {len(mapping)} converted migrations")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
